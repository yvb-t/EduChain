const axios = require('axios');
const FormData = require('form-data');
const fs = require('fs');
const path = require('path');

const API_URL = 'http://localhost:5000/api';

async function testCreateRequest() {
    try {
        console.log("1️⃣ Logging in...");
        const loginRes = await axios.post(`${API_URL}/auth/login`, {
            email: "verified_student@educhain.com",
            password: "password123"
        });
        const token = loginRes.data.token;
        const studentId = loginRes.data.user.id;
        console.log("✅ Logged in. Token:", token.substring(0, 20) + "...");

        // Cleanup: Delete existing active requests
        console.log("🧹 Cleaning up existing requests...");
        try {
            const existingRes = await axios.get(`${API_URL}/scholarships?studentId=${studentId}`, {
                headers: { 'Authorization': `Bearer ${token}` }
            });

            for (const req of existingRes.data) {
                if (req.status === 'ACTIVE') {
                    console.log(`   Deleting request ${req.id}...`);
                    await axios.delete(`${API_URL}/scholarships/${req.id}`, {
                        headers: { 'Authorization': `Bearer ${token}` }
                    });
                }
            }
        } catch (err) {
            console.log("   No existing requests or cleanup failed (ignoring).");
        }

        console.log("2️⃣ Creating Request...");
        const form = new FormData();
        form.append('title', 'Test Scholarship Request');
        form.append('description', 'This is a test request generated by the verification script.');
        form.append('amount', '5000');
        form.append('type', 'MICRO');
        form.append('category', 'Tuition');
        form.append('studentId', studentId);
        form.append('authority_number', 'TEST_AUTH_123');
        form.append('institution_contact_number', '9876543210');

        // JSON Fields as Strings (The Fix)
        form.append('personal_details', JSON.stringify({
            parentName: "Test Parent",
            currentAddress: "123 Test St"
        }));
        form.append('expenses', JSON.stringify([
            { id: 1, item: "Books", cost: "2000" },
            { id: 2, item: "Fees", cost: "3000" }
        ]));

        // Create a dummy proof file (> 5KB to pass AI check)
        const dummyFilePath = path.join(__dirname, 'dummy_proof.pdf');
        const buffer = Buffer.alloc(1024 * 10); // 10KB
        buffer.fill('A');
        fs.writeFileSync(dummyFilePath, buffer);
        form.append('proof', fs.createReadStream(dummyFilePath));

        const config = {
            headers: {
                ...form.getHeaders(),
                'Authorization': `Bearer ${token}`
            }
        };

        const res = await axios.post(`${API_URL}/scholarships`, form, config);
        console.log("✅ Request Created Successfully!");
        console.log("Response:", res.data);

        // Cleanup
        fs.unlinkSync(dummyFilePath);

    } catch (error) {
        console.error("❌ Request Failed!");
        if (error.response) {
            console.error("Status:", error.response.status);
            console.error("Data:", error.response.data);
        } else {
            console.error(error.message);
        }
    }
}

testCreateRequest();
